"""Image providers: local Graphviz diagrams, Pexels/Unsplash stock photos, Gemini generation.

Each provider returns (image_bytes, credit_or_empty) or raises.
"""
from __future__ import annotations

import os
import shutil
from pathlib import Path
from typing import Tuple

import httpx

from ..config import get_settings

_GRAPHVIZ_DIRS = [r"C:\Program Files\Graphviz\bin", r"C:\Program Files (x86)\Graphviz\bin"]


def graphviz_available() -> bool:
    if shutil.which("dot"):
        return True
    for d in _GRAPHVIZ_DIRS:
        if Path(d, "dot.exe").exists():
            os.environ["PATH"] = d + os.pathsep + os.environ.get("PATH", "")
            return True
    return False


def render_dot(dot_source: str) -> Tuple[bytes, str]:
    if not graphviz_available():
        raise RuntimeError("Graphviz 'dot' not found (winget install Graphviz.Graphviz)")
    import graphviz

    return graphviz.Source(dot_source).pipe(format="png"), ""


def pexels(query: str) -> Tuple[bytes, str]:
    key = get_settings().pexels_api_key
    if not key:
        raise RuntimeError("PEXELS_API_KEY not set")
    r = httpx.get(
        "https://api.pexels.com/v1/search",
        params={"query": query, "per_page": 1, "orientation": "landscape"},
        headers={"Authorization": key},
        timeout=30,
    )
    r.raise_for_status()
    photos = r.json().get("photos") or []
    if not photos:
        raise RuntimeError(f"no Pexels result for {query!r}")
    p = photos[0]
    img = httpx.get(p["src"]["large"], timeout=60, follow_redirects=True)
    img.raise_for_status()
    return img.content, f"Photo by {p.get('photographer', 'unknown')} on Pexels"


def unsplash(query: str) -> Tuple[bytes, str]:
    key = get_settings().unsplash_access_key
    if not key:
        raise RuntimeError("UNSPLASH_ACCESS_KEY not set")
    headers = {"Authorization": f"Client-ID {key}"}
    r = httpx.get(
        "https://api.unsplash.com/search/photos",
        params={"query": query, "per_page": 1, "orientation": "landscape"},
        headers=headers,
        timeout=30,
    )
    r.raise_for_status()
    results = r.json().get("results") or []
    if not results:
        raise RuntimeError(f"no Unsplash result for {query!r}")
    p = results[0]
    # Unsplash API guidelines: trigger the download endpoint when a photo is used.
    try:
        httpx.get(p["links"]["download_location"], headers=headers, timeout=15)
    except Exception:
        pass
    img = httpx.get(p["urls"]["regular"], timeout=60, follow_redirects=True)
    img.raise_for_status()
    return img.content, f"Photo by {p.get('user', {}).get('name', 'unknown')} on Unsplash"


def gemini(prompt: str) -> Tuple[bytes, str]:
    """Raw image bytes generated by Gemini (moved from Blog_Writer._gemini_generate_image_bytes)."""
    s = get_settings()
    if not s.google_api_key:
        raise RuntimeError("GOOGLE_API_KEY not set")
    from google import genai
    from google.genai import types

    client = genai.Client(api_key=s.google_api_key)
    resp = client.models.generate_content(
        model=s.gemini_image_model,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_modalities=["IMAGE"],
            safety_settings=[
                types.SafetySetting(category="HARM_CATEGORY_DANGEROUS_CONTENT", threshold="BLOCK_ONLY_HIGH")
            ],
        ),
    )
    # Depending on SDK version, parts may hang off resp.candidates[0].content.parts
    parts = getattr(resp, "parts", None)
    if not parts and getattr(resp, "candidates", None):
        try:
            parts = resp.candidates[0].content.parts
        except Exception:
            parts = None
    if not parts:
        raise RuntimeError("No image content returned (safety/quota/SDK change).")
    for part in parts:
        inline = getattr(part, "inline_data", None)
        if inline and getattr(inline, "data", None):
            return inline.data, "AI-generated image"
    raise RuntimeError("No inline image bytes found in response.")


def available() -> dict:
    s = get_settings()
    return {
        "graphviz": graphviz_available(),
        "pexels": bool(s.pexels_api_key),
        "unsplash": bool(s.unsplash_access_key),
        "gemini": bool(s.google_api_key),
    }
